#!/usr/bin/env node
// 把收集词库原始数据按标签组拆成 ~400KB 的按需加载分片。
//
//   node scripts/split-collected-segments.mjs
//
// 输出到 src/components/prompt-library-segments/：
//   seg-000.mjs ... seg-NNN.mjs   每个分片导出原始 TSV 文本（metadata 行子集）
//   seg-phrases.mjs               完整短语行
//   index.mjs                     分片注册表：分组 -> 分片、计数、总数
//
// 浏览器端 loadCollectedPromptItems 只按注册表加载所需分片；分片是 metadata
// 行的子集，行格式与 ALL_tag_metadata.tsv 一致，可复用 parseTagMetadata。
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SOURCE_DIR = join(ROOT, 'prompts_collected/extracted');
const OUT_DIR = join(ROOT, 'src/components/prompt-library-segments');
const MAX_SEGMENT_BYTES = 380 * 1024;

const metadataLines = readFileSync(join(SOURCE_DIR, 'ALL_tag_metadata.tsv'), 'utf8').split(/\r?\n/).filter(Boolean);
const phraseLines = readFileSync(join(SOURCE_DIR, 'ALL_prompt_phrases.txt'), 'utf8').split(/\r?\n/).filter(Boolean);

const tagGroups = new Map();
for (const line of metadataLines) {
  const tag = line.slice(0, line.indexOf('\t'));
  const group = line.split('\t')[2].trim() || '未分类';
  if (!tagGroups.has(group)) tagGroups.set(group, []);
  tagGroups.get(group).push(line);
}

const groupOrder = [...tagGroups.entries()]
  .map(([group, lines]) => [group, lines, Buffer.byteLength(lines.join('\n'))])
  .sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]));

const segments = [];
const groupSegments = new Map();

function addSegment(id, groups, lines, kind = 'tags') {
  segments.push({ id, groups, count: lines.length, kind });
  writeFileSync(join(OUT_DIR, `${id}.mjs`), `export default ${JSON.stringify(lines.join('\n'))};\n`);
  for (const group of groups) {
    if (!groupSegments.has(group)) groupSegments.set(group, []);
    groupSegments.get(group).push(id);
  }
}

let index = 0;
for (const [group, lines] of groupOrder) {
  const text = lines.join('\n');
  if (Buffer.byteLength(text) <= MAX_SEGMENT_BYTES) {
    addSegment(`seg-${String(index++).padStart(3, '0')}`, [group], lines);
    continue;
  }
  const chunkCount = Math.ceil(Buffer.byteLength(text) / MAX_SEGMENT_BYTES);
  const perChunk = Math.ceil(lines.length / chunkCount);
  for (let offset = 0; offset < lines.length; offset += perChunk) {
    addSegment(`seg-${String(index++).padStart(3, '0')}`, [group], lines.slice(offset, offset + perChunk));
  }
}

const phrasesId = 'seg-phrases';
addSegment(phrasesId, [], phraseLines, 'phrases');
const tagCount = segments.filter(segment => segment.id !== phrasesId).reduce((sum, segment) => sum + segment.count, 0);

const tagGroupsExport = Object.fromEntries(
  [...groupSegments.entries()]
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([group, ids]) => [group, { count: tagGroups.get(group).length, segments: ids }]),
);

writeFileSync(join(OUT_DIR, 'index.mjs'), [
  '// Generated by scripts/split-collected-segments.mjs. Do not edit.',
  `export const COLLECTED_TOTAL_TAGS = ${tagCount};`,
  `export const COLLECTED_PHRASES_SEGMENT = '${phrasesId}';`,
  `export const COLLECTED_SEGMENTS = ${JSON.stringify(segments, null, 2)};`,
  `export const COLLECTED_TAG_GROUPS = ${JSON.stringify(tagGroupsExport, null, 2)};`,
  '',
].join('\n'));

console.log(`segments: ${segments.length}, tags: ${tagCount}, phrases: ${phraseLines.length}, groups: ${groupSegments.size}`);
