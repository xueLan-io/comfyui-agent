#!/usr/bin/env node
// 收集词库去重:
//   1. 同一标签同时存在"下划线/空格"两种写法时,保留下划线写法(Danbooru 标准,含真实计数),删除空格写法
//   2. 短语库中与标签完全相同的行删除
// 重新生成分片与注册表(与 scripts/split-collected-segments.mjs 同算法)。
//   node scripts/dedup-collected-library.mjs
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT_DIR = join(ROOT, 'src/components/prompt-library-segments');
const MAX_SEGMENT_BYTES = 380 * 1024;

const tagLines = new Map();
for (const file of readdirSync(OUT_DIR).filter(f => /^seg-\d{3}\.mjs$/.test(f))) {
  const body = readFileSync(join(OUT_DIR, file), 'utf8').match(/export default "([\s\S]*?)";\n$/);
  for (const line of JSON.parse('"' + body[1] + '"').split(/\r?\n/).filter(Boolean)) {
    const tag = line.slice(0, line.indexOf('\t'));
    tagLines.set(tag, line);
  }
}

const spacedMap = new Map();
for (const tag of tagLines.keys()) {
  const spaced = tag.replaceAll('_', ' ');
  if (!spacedMap.has(spaced)) spacedMap.set(spaced, []);
  spacedMap.get(spaced).push(tag);
}

let removed = 0;
const removedExamples = [];
for (const [spaced, tags] of spacedMap) {
  if (tags.length < 2) continue;
  const underscoreTags = tags.filter(t => t.includes('_'));
  const keep = new Set(underscoreTags.length > 0 ? underscoreTags : tags.slice(0, 1));
  for (const tag of tags) {
    if (!keep.has(tag)) {
      tagLines.delete(tag);
      removed++;
      if (removedExamples.length < 15) removedExamples.push(`${spaced}  (drop: ${tag})`);
    }
  }
}
console.log(`tag dups removed: ${removed}`);

const phraseBody = readFileSync(join(OUT_DIR, 'seg-phrases.mjs'), 'utf8').match(/export default "([\s\S]*?)";\n$/);
const phraseLines = JSON.parse('"' + phraseBody[1] + '"').split(/\r?\n/).filter(Boolean);
const keptTags = new Set([...tagLines.keys()].map(t => t.replaceAll('_', ' ')));
const keptPhrases = [];
let phraseRemoved = 0;
for (const line of phraseLines) {
  const promptPart = line.replace(/,\s*'[^']*'$/, '').trim();
  if (keptTags.has(promptPart)) {
    phraseRemoved++;
    continue;
  }
  keptPhrases.push(line);
}
console.log(`phrase dups removed: ${phraseRemoved}`);

const groups = new Map();
for (const line of tagLines.values()) {
  const group = line.split('\t')[2]?.trim() || '未分组';
  if (!groups.has(group)) groups.set(group, []);
  groups.get(group).push(line);
}
const groupOrder = [...groups.entries()]
  .map(([group, lines]) => [group, lines, Buffer.byteLength(lines.join('\n'))])
  .sort((a, b) => b[1].length - a[1].length || a[0].localeCompare(b[0]));

const segments = [];
const groupSegments = new Map();
function addSegment(id, group, lines) {
  segments.push({ id, groups: group ? [group] : [], count: lines.length });
  writeFileSync(join(OUT_DIR, `${id}.mjs`), `export default ${JSON.stringify(lines.join('\n'))};\n`);
  if (group) {
    if (!groupSegments.has(group)) groupSegments.set(group, []);
    groupSegments.get(group).push(id);
  }
}
let index = 0;
for (const [group, lines] of groupOrder) {
  const text = lines.join('\n');
  if (Buffer.byteLength(text) <= MAX_SEGMENT_BYTES) {
    addSegment(`seg-${String(index++).padStart(3, '0')}`, group, lines);
    continue;
  }
  const perChunk = Math.ceil(lines.length / Math.ceil(Buffer.byteLength(text) / MAX_SEGMENT_BYTES));
  for (let offset = 0; offset < lines.length; offset += perChunk) {
    addSegment(`seg-${String(index++).padStart(3, '0')}`, group, lines.slice(offset, offset + perChunk));
  }
}
const phrasesId = 'seg-phrases';
segments.push({ id: phrasesId, groups: [], count: keptPhrases.length });
writeFileSync(join(OUT_DIR, `${phrasesId}.mjs`), `export default ${JSON.stringify(keptPhrases.join('\n'))};\n`);

const tagCount = segments.filter(s => s.id !== phrasesId).reduce((sum, s) => sum + s.count, 0);
const tagGroupsExport = Object.fromEntries(
  [...groupSegments.entries()]
    .sort((a, b) => a[0].localeCompare(b[0]))
    .map(([group, ids]) => [group, { count: groups.get(group).length, segments: ids }]),
);
writeFileSync(join(OUT_DIR, 'index.mjs'), [
  '// Generated by scripts/split-collected-segments.mjs. Do not edit.',
  `export const COLLECTED_TOTAL_TAGS = ${tagCount};`,
  `export const COLLECTED_PHRASES_SEGMENT = '${phrasesId}';`,
  `export const COLLECTED_SEGMENTS = ${JSON.stringify(segments, null, 2)};`,
  `export const COLLECTED_TAG_GROUPS = ${JSON.stringify(tagGroupsExport, null, 2)};`,
  '',
].join('\n'));

console.log(`segments: ${segments.length}, tags: ${tagCount}, phrases: ${keptPhrases.length}, groups: ${groupSegments.size}`);
console.log('removed examples:');
for (const e of removedExamples) console.log('  ', e);
